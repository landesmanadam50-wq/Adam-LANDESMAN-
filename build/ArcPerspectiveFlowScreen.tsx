import { useCallback, useState } from "react";
import { Pressable, ScrollView, StyleSheet, Text, View } from "react-native";
import { SafeAreaView } from "react-native-safe-area-context";
import { router, useFocusEffect } from "expo-router";

import {
  chooseArcPerspectiveMood,
  completeArcPerspectiveSession,
  createArcPerspectiveEvent,
  createArcPerspectiveSession,
  generateArcPerspectiveEventId,
  generateArcPerspectiveSessionId,
  seedArcPerspectiveSessionFromEvent,
} from "../arc/arcPerspective.ts";
import type { ArcPerspectiveMode, ArcPerspectiveSession } from "../arc/arcPerspective.ts";
import { linkArcPerspectiveToArcGymSituation } from "../arc/arcGym.ts";
import type { ArcGymSituation } from "../arc/arcGym.ts";
import { findActiveTask } from "../arc/tasks.ts";
import { STANDALONE_ARC_TASK_ID } from "../arc/newArcLiveTypes.ts";
import { handleArcPerspectiveCheckInChoice } from "../data/emotionalCheckInRouting.ts";
import {
  clearArcPerspectiveInProgress,
  loadArcGymSituations,
  loadArcPerspectiveEvents,
  loadArcPerspectiveInProgress,
  loadTasks,
  saveArcPerspectiveInProgress,
  upsertArcGymSituationEntry,
  upsertArcPerspectiveEventEntry,
  upsertArcPerspectiveSessionEntry,
} from "../data/storage.ts";
import ArcPerspectiveFlow from "../live/components/ArcPerspectiveFlow.tsx";

/**
 * build/ArcPerspectiveFlowScreen.tsx (route /arc-perspective/[id])
 *
 * ARC Perspective task: the ONE screen both entry points (ARC Gym's own
 * saved events, and the real-time Home button) open -- `id` is the
 * ArcPerspectiveSession's own id, generated by the caller BEFORE
 * navigating here so it stays stable across the ARC mood-check-in
 * round-trip (see live/NewArcLiveScreen.tsx's own returnToTask()
 * arcPerspectiveId branch, which routes back to this exact route/id).
 *
 * The event template (arc/arcPerspective.ts's own ArcPerspectiveEvent)
 * is created here exactly once, from this screen's own "event" step,
 * for a brand-new event (`eventId` param "new"/absent) -- never
 * recreated or overwritten on a later focus, and never silently
 * rewritten by a resumed/re-practiced session (editing an existing
 * saved event is only ever done from its own detail screen).
 */
export default function ArcPerspectiveFlowScreen({ id, mode, eventId }: { id: string; mode: ArcPerspectiveMode; eventId?: string | null }) {
  const [session, setSession] = useState<ArcPerspectiveSession | null>(null);
  const [eventPersisted, setEventPersisted] = useState(false);
  const [situations, setSituations] = useState<ArcGymSituation[]>([]);
  const [finished, setFinished] = useState<ArcPerspectiveSession | null>(null);

  useFocusEffect(
    useCallback(() => {
      (async () => {
        const [progress, allSituations] = await Promise.all([loadArcPerspectiveInProgress(), loadArcGymSituations()]);
        setSituations(allSituations);

        if (progress && progress.id === id) {
          setSession(progress.completedAt ? null : progress);
          setFinished(progress.completedAt ? progress : null);
          setEventPersisted(true);
          return;
        }

        const hasRealEventId = !!eventId && eventId !== "new";
        if (hasRealEventId) {
          const events = await loadArcPerspectiveEvents();
          const existingEvent = events.find((candidate) => candidate.id === eventId) ?? null;
          // The route's own `id` param is what live/NewArcLiveScreen.tsx's
          // returnToTask() will route back to -- it must be this
          // session's real id, never the one createArcPerspectiveSession
          // generates internally for itself.
          const fresh = { ...createArcPerspectiveSession(mode, eventId as string, null, new Date().toISOString()), id };
          setSession(existingEvent ? seedArcPerspectiveSessionFromEvent(fresh, existingEvent) : fresh);
          setEventPersisted(true);
          setFinished(null);
          return;
        }

        const activeTaskId = mode === "real_time" ? findActiveTask(await loadTasks())?.id ?? null : null;
        const freshEventId = generateArcPerspectiveEventId();
        setSession({ ...createArcPerspectiveSession(mode, freshEventId, activeTaskId, new Date().toISOString()), id });
        setEventPersisted(false);
        setFinished(null);
      })();
    }, [id, mode, eventId])
  );

  async function handleChange(next: ArcPerspectiveSession) {
    setSession(next);
    await saveArcPerspectiveInProgress(next);
    // The event template is created exactly once, the first time a
    // brand-new session leaves its own "event" step -- never for a
    // session that started from an already-existing saved event (that
    // one's template is only ever edited on its own detail screen).
    if (!eventPersisted && next.currentStep !== "event") {
      await upsertArcPerspectiveEventEntry({
        ...createArcPerspectiveEvent(next.eventId, next.startedAt),
        eventDescription: next.eventDescription,
        initialInterpretation: next.initialInterpretation,
        desiredInterpretationPreset: next.desiredInterpretationPreset.trim() || null,
      });
      setEventPersisted(true);
    }
  }

  async function handleCancel() {
    await clearArcPerspectiveInProgress();
    router.back();
  }

  async function handleMoodCheckIn(choice: "full_arc" | "shortened_arc") {
    if (!session) return;
    const withMood = chooseArcPerspectiveMood(session, choice);
    setSession(withMood);
    await saveArcPerspectiveInProgress(withMood);
    const taskId = session.mode === "planned" ? STANDALONE_ARC_TASK_ID : session.activeTaskId ?? STANDALONE_ARC_TASK_ID;
    await handleArcPerspectiveCheckInChoice(choice, { arcPerspectiveId: session.id, taskId });
  }

  async function handleFinish(finishedSession: ArcPerspectiveSession) {
    const now = new Date().toISOString();
    if (finishedSession.linkedArcGymSituationId) {
      const allSituations = await loadArcGymSituations();
      const situation = allSituations.find((candidate) => candidate.id === finishedSession.linkedArcGymSituationId);
      if (situation) await upsertArcGymSituationEntry(linkArcPerspectiveToArcGymSituation(situation, finishedSession.id, finishedSession.newInterpretation, now));
    }
    const completed = completeArcPerspectiveSession(finishedSession, now);
    await upsertArcPerspectiveSessionEntry(completed);
    await clearArcPerspectiveInProgress();
    setSession(null);
    setFinished(completed);
  }

  function practiceAgain() {
    if (!finished) return;
    router.replace({ pathname: "/arc-perspective/[id]", params: { id: generateArcPerspectiveSessionId(), mode: finished.mode, eventId: finished.eventId } });
  }

  if (finished) {
    return (
      <SafeAreaView style={styles.safeArea}>
        <ScrollView contentContainerStyle={styles.content}>
          <Text style={styles.title}>ARC Perspective — סיכום</Text>
          <Text style={styles.summaryLabel}>אירוע</Text>
          <Text style={styles.summaryText}>{finished.eventDescription}</Text>
          <Text style={styles.summaryLabel}>פרשנות ראשונית</Text>
          <Text style={styles.summaryText}>{finished.initialInterpretation}</Text>
          <Text style={styles.summaryLabel}>פרשנות חדשה</Text>
          <Text style={styles.summaryText}>{finished.newInterpretation}</Text>
          <Text style={styles.summaryLabel}>מצב תרגול</Text>
          <Text style={styles.summaryText}>{finished.mode === "planned" ? "מראש" : "בזמן אמת"}</Text>
          {!!finished.linkedArcGymSituationId && (
            <Pressable style={styles.secondaryButton} onPress={() => router.push({ pathname: "/arc-gym/situation/[id]", params: { id: finished.linkedArcGymSituationId! } })}>
              <Text style={styles.secondaryButtonText}>פתח ARC Behaviour</Text>
            </Pressable>
          )}
          <Pressable style={styles.secondaryButton} onPress={practiceAgain}>
            <Text style={styles.secondaryButtonText}>תרגל שוב</Text>
          </Pressable>
          <Pressable
            style={styles.primaryButton}
            onPress={() => (finished.mode === "real_time" ? router.replace("/") : router.replace({ pathname: "/arc-gym/perspective/[id]", params: { id: finished.eventId } }))}
          >
            <Text style={styles.primaryButtonText}>סיום</Text>
          </Pressable>
        </ScrollView>
      </SafeAreaView>
    );
  }

  if (!session) {
    return (
      <SafeAreaView style={styles.safeArea}>
        <View style={styles.content}>
          <Text style={styles.hint}>טוען...</Text>
        </View>
      </SafeAreaView>
    );
  }

  return (
    <SafeAreaView style={styles.safeArea}>
      <ScrollView contentContainerStyle={styles.content}>
        <Text style={styles.title}>ARC Perspective — שינוי פרשנות</Text>
        <ArcPerspectiveFlow
          session={session}
          onChange={handleChange}
          onCancel={handleCancel}
          onMoodCheckIn={handleMoodCheckIn}
          situations={situations}
          onCreateNewBehaviour={() => router.push("/arc-gym")}
          onFinish={handleFinish}
        />
      </ScrollView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  safeArea: { flex: 1, backgroundColor: "#fff" },
  content: { flexGrow: 1, padding: 20 },
  hint: { fontSize: 14, textAlign: "right", color: "#666" },
  title: { fontSize: 20, fontWeight: "700", textAlign: "right", marginBottom: 18 },
  summaryLabel: { fontSize: 13, fontWeight: "700", textAlign: "right", color: "#0a7ea4", marginTop: 12 },
  summaryText: { fontSize: 15, textAlign: "right", color: "#333", marginTop: 2 },
  primaryButton: { backgroundColor: "#0a7ea4", paddingVertical: 16, borderRadius: 12, alignItems: "center", marginTop: 20 },
  primaryButtonText: { color: "#fff", fontWeight: "700", fontSize: 16 },
  secondaryButton: { borderWidth: 1, borderColor: "#0a7ea4", paddingVertical: 14, borderRadius: 12, alignItems: "center", marginTop: 12 },
  secondaryButtonText: { color: "#0a7ea4", fontWeight: "700", fontSize: 15 },
});
